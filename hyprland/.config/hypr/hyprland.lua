-- See https://wiki.hypr.land/Configuring/Basics/Monitors/
-- Format: output, resolution@refresh, position, scale
--
-- Display mode management (cycled by scripts/display-cycle.sh):
--   laptop   -> only the laptop screen (eDP-1) is on
--   both     -> laptop + Samsung (DP-2) both on
--   external -> only the Samsung (DP-2) is on
--
--   * Preference stored in ~/.config/hypr/state/display-mode.
--   * Falls back to "laptop" whenever the Samsung (DP-2) is NOT connected, so
--     we are never left without a usable screen.
--   * Cycled by the keybind + scripts/display-cycle.sh, then `hyprctl reload`.
local HOME = os.getenv("HOME")

local function display_mode()
	local f = io.open(HOME .. "/.config/hypr/state/display-mode", "r")
	if not f then return "both" end
	local v = f:read("*a") or ""
	f:close()
	v = v:gsub("%s+", "")
	if v == "laptop" or v == "both" or v == "external" then return v end
	return "both"
end

-- Samsung present? hl.get_monitor returns nil if the output is not connected.
local samsung_connected = hl.get_monitor("DP-2") ~= nil
-- Without the Samsung connected, the only sensible mode is "laptop".
local mode              = samsung_connected and display_mode() or "laptop"

local laptop_on   = (mode == "laptop" or mode == "both")
local external_on = samsung_connected and (mode == "both" or mode == "external")

-- Laptop panel (4K) at scale 2.0 -> effective 1920x1080, placed at top-left.
hl.monitor({
	output   = "eDP-1",
	mode     = "3840x2160@60",
	position = "0x0",
	scale    = 2.0,
	disabled = not laptop_on,
})

-- Samsung 4K monitor, placed to the right of the laptop (x = 1920 logical px).
-- Scale 1.25 -> effective 3072x1728 (a bit smaller UI / more space).
hl.monitor({
	output   = "DP-2",
	mode     = "3840x2160@60",
	position = "1920x0",
	scale    = 1.25,
	disabled = not external_on,
})

-- Fallback for any other monitor that gets plugged in.
hl.monitor({
	output   = "",
	mode     = "preferred",
	position = "auto",
	scale    = "auto",
})

-- Re-evaluate the laptop-screen rule when the Samsung is docked/undocked.
-- Only react to DP-2 so we don't loop when eDP-1 itself is added/removed.
hl.on("monitor.added", function(mon)
	if mon and mon.name == "DP-2" then
		hl.exec_cmd("hyprctl reload")
	end
end)

hl.on("monitor.removed", function(mon)
	if mon and mon.name == "DP-2" then
		hl.exec_cmd("hyprctl reload")
	end
end)

