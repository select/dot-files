-- Load pywal-generated colors (~/.cache/wal/colors-hyprland.conf is hyprlang
-- format: "$colorN = rgba(r,g,b,a)"). We parse it into a Lua table here so the
-- pywal workflow keeps working: regenerate colors then `hyprctl reload`.
local function load_wal()
	local colors = {}
	local f = io.open(os.getenv("HOME") .. "/.cache/wal/colors-hyprland.conf", "r")
	if not f then return colors end
	for line in f:lines() do
		local k, v = line:match("^%s*%$(%S+)%s*=%s*(.-)%s*$")
		if k and v then colors[k] = v end
	end
	f:close()
	return colors
end

